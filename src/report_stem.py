"""Section 10 of report.md: Porter-stemmed Stage 1 experiment. All numbers come from results/ext_stem_*.csv; directional
statements are generated by the same decision rule as section 9 (report_ext.verdict)."""
import pandas as pd
import config as C
from analysis import md
from report_ext import LAB, with_verdict

R = C.RESULTS_DIR


def stem_section(main_t, main_dev):
    summ = pd.read_csv(R / "ext_stem_stage1_summary.csv")
    mt = pd.read_csv(R / "ext_stem_metrics_test.csv").set_index("model")
    md_ = pd.read_csv(R / "ext_stem_metrics_dev.csv").set_index("model")
    sig = with_verdict(pd.read_csv(R / "ext_stem_significance.csv"))
    sfr = pd.read_csv(R / "ext_single_feature_reranks.csv")
    stage = summ.rename(columns={"stage1": "Stage 1", "recall@100_micro": "Recall@100 micro", "recall@100_macro": "Recall@100 macro",
                                 "frac_queries_no_relevant_candidate": "frac. queries with no relevant candidate",
                                 "n_queries_no_relevant_candidate": "#such queries", "frac_queries_lt100_cand": "frac. queries < 100 candidates",
                                 "oracle_NDCG@10": "oracle NDCG@10", "oracle_MAP": "oracle MAP", "stage1_NDCG@10": "Stage-1 order NDCG@10",
                                 "stage1_MAP": "Stage-1 order MAP"})
    stage = stage[["Stage 1", "split", "n_queries", "Recall@100 micro", "Recall@100 macro", "frac. queries with no relevant candidate",
                   "#such queries", "frac. queries < 100 candidates", "oracle NDCG@10", "oracle MAP", "Stage-1 order NDCG@10", "Stage-1 order MAP"]]
    names = {"stemmed_bm25": "BM25, Porter-stemmed Stage 1 (alone)", "linreg": "Linear regression on stemmed candidates",
             "logreg": "Logistic regression on stemmed candidates", "ranksvm_sampled": "RankSVM sampled on stemmed candidates"}
    rows = [{"system": "BM25, unstemmed Stage 1 (main run)", "C": "", "dev NDCG@10": main_dev.loc["bm25", "NDCG@10"], "test MAP": main_t.loc["bm25", "MAP"],
             "test NDCG@5": main_t.loc["bm25", "NDCG@5"], "test NDCG@10": main_t.loc["bm25", "NDCG@10"], "test pair acc": main_t.loc["bm25", "pair_acc_micro"]}]
    for n in names:
        r = mt.loc[n]
        rows.append({"system": names[n], "C": "" if pd.isna(r["C"]) else f"{r['C']:g}", "dev NDCG@10": md_.loc[n, "NDCG@10"], "test MAP": r["MAP"],
                     "test NDCG@5": r["NDCG@5"], "test NDCG@10": r["NDCG@10"], "test pair acc": r["pair_acc_micro"]})
    cols = ["model", "metric", "mean_delta", "ci95_lo", "ci95_hi", "p_ttest", "p_wilcoxon", "p_ttest_holm", "cohen_dz", "verdict"]
    a = sig[sig.comparison == "(a) vs unstemmed BM25"]
    b = sig[sig.comparison == "(b) vs stemmed BM25 alone"]
    show = lambda t: md(t.assign(model=t["model"].map(lambda m: names.get(m, m)))[cols], "{:.4f}")
    a_st = a[a.model == "stemmed_bm25"]
    a_m = a[a.model != "stemmed_bm25"]
    cnt = lambda t, metric, kind: int(((t.metric == metric) & (t.verdict == kind)).sum())
    n_a_nd, n_a_ap = cnt(a_m, "ndcg10", "improvement supported"), cnt(a_m, "ap", "improvement supported")
    n_b_nd, n_b_ap = cnt(b, "ndcg10", "no supported difference"), cnt(b, "ap", "no supported difference")
    sup_b_nd = list(b[(b.metric == "ndcg10") & (b.verdict != "no supported difference")]["model"].map(names))
    sup_b_ap = [f"{names[r.model]} ({r.verdict}, {r.mean_delta:+.4f})" for r in b[(b.metric == "ap") & (b.verdict != "no supported difference")].itertuples()]
    st_v = {m: a_st[a_st.metric == m].iloc[0] for m in ("ndcg10", "ap")}
    chosen = {n: mt.loc[n, "C"] for n in ("logreg", "ranksvm_sampled")}
    edge_txt = ", ".join(f"{LAB[n]} C = {c:g}" for n, c in chosen.items() if c in (C.C_GRID[0], C.C_GRID[-1]))
    rr = sfr[(sfr.split == "test") & (sfr.model == "rerank:bm25_stem_comb")].iloc[0]
    s_te = summ[(summ.stage1 == "Porter-stemmed") & (summ.split == "test")].iloc[0]
    u_te = summ[(summ.stage1 != "Porter-stemmed") & (summ.split == "test")].iloc[0]
    max_a = a_m[a_m.metric == "ndcg10"]["mean_delta"].abs().max()
    max_b = b[b.metric == "ndcg10"]["mean_delta"].abs().max()
    edge_sentence = (f"The selected C is at the edge of the pre-specified grid for {edge_txt}; the grid was not extended (C may only be chosen from the pre-specified grid)."
                     if edge_txt else "No chosen C is at the edge of the grid.")
    if n_b_nd == 3 and n_b_ap == 3:
        attributable = "The gain over the original baseline is therefore attributable to the stemmed Stage 1, not to the learned re-rankers."
    elif n_b_nd == 3:
        attributable = ("On NDCG@10 the gain over the original baseline is attributable to the stemmed Stage 1 (no learned model differs from stemmed BM25 alone); "
                        "on AP the model(s) listed above add a small supported difference on top of it.")
    else:
        attributable = "See the table for which models add something on top of stemmed BM25."
    text = f"""## 10. Additional experiment: Porter-stemmed Stage 1

*Added after section 9; all earlier results are unchanged.* Stage 1 is rebuilt with BM25 (k1 = {C.BM25_K1}, b = {C.BM25_B}, same code) on **Porter-stemmed** tokens (own stemmer, `src/porter.py`; stop-words removed before stemming; queries and documents analysed identically), Top-{C.TOP_K} per query. The 14 v1 features are recomputed **in the same stemmed space on the new candidates** (so `bm25_comb`, `bm25_rank`, `lm_dirichlet`, ... all refer to stemmed tokens). Protocol identical to the main run: official split, scaler fitted on train only, C chosen on dev only (NDCG@10), test scored once; models: linear regression, logistic regression, sampled Ranking SVM (squared hinge, same seed as the main run). Nothing about Stage 1 was tuned (it has no hyper-parameter), but there is a forking-paths caveat: stemming was tried *after* the v2 experiment (section 9.3) had shown test-set gains for a stemmed BM25 feature, so this is a follow-up on the same test queries, not an independent replication. Files: `ext_stem_stage1_summary.csv`, `ext_stem_candidate_recall.csv`, `ext_stem_metrics_test.csv`, `ext_stem_metrics_dev.csv`, `ext_stem_significance.csv`, `ext_stem_per_query_test.csv`, `ext_stem_weights.csv`, `ext_stem_tuning_dev.csv`.

### 10.1 Stage 1 side by side (unstemmed vs stemmed; Top-{C.TOP_K}, all splits)

{md(stage, "{:.4f}")}

Oracle = re-ranking the same candidates with the true labels (an upper bound that uses labels; for context only). "Stage-1 order" = the BM25 ranking itself. On test, stemming changes Recall@100 (micro) from {u_te['recall@100_micro']:.4f} to {s_te['recall@100_micro']:.4f}, Recall@100 (macro) from {u_te['recall@100_macro']:.4f} to {s_te['recall@100_macro']:.4f}, the fraction of queries without any relevant candidate from {u_te['frac_queries_no_relevant_candidate']:.4f} to {s_te['frac_queries_no_relevant_candidate']:.4f}, and the oracle NDCG@10 from {u_te['oracle_NDCG@10']:.4f} to {s_te['oracle_NDCG@10']:.4f}. These describe the candidate sets and carry no significance test; the comparison of the *rankings* is in 10.2.

### 10.2 Re-ranking results (test split)

{md(pd.DataFrame(rows), "{:.4f}")}

{edge_sentence}

**(a) Paired tests vs the unstemmed BM25 of the main run** (same {int(a['n_queries'].iloc[0])} test queries; Holm over the 4 comparisons per metric)

{show(a)}

**(b) Paired tests vs stemmed BM25 alone** (does learning add anything on top of the stemmed Stage 1? Holm over 3 comparisons per metric)

{show(b)}

Reading (generated from the decision rule: both raw p < 0.05 and CI excluding 0; labels use raw p, Holm shown):

* Stemmed BM25 alone vs unstemmed BM25: NDCG@10 **{st_v['ndcg10']['verdict']}** (mean difference {st_v['ndcg10']['mean_delta']:+.4f}, CI [{st_v['ndcg10']['ci95_lo']:+.4f}, {st_v['ndcg10']['ci95_hi']:+.4f}]); AP **{st_v['ap']['verdict']}** ({st_v['ap']['mean_delta']:+.4f}). For comparison, re-ranking the *unstemmed* Top-100 by stemmed BM25 (section 9.3) gives NDCG@10 {rr['NDCG@10']:.4f}, a descriptively lower value (no paired test was run for this comparison), consistent with the stemmed candidate set contributing to the gain.
* Learned models vs unstemmed BM25: improvement supported for **{n_a_nd} of 3** models on NDCG@10 and **{n_a_ap} of 3** on AP.
* Learned models vs stemmed BM25 alone: **{n_b_nd} of 3** show no supported difference on NDCG@10 ({'no model differs' if not sup_b_nd else 'supported difference for: ' + ', '.join(sup_b_nd)}) and **{n_b_ap} of 3** on AP ({'no model differs' if not sup_b_ap else 'supported difference for: ' + ', '.join(sup_b_ap)}). {attributable}
* Practical size: the largest mean NDCG@10 difference to unstemmed BM25 among the learned models is {max_a:.4f}, and to stemmed BM25 alone {max_b:.4f} (practical threshold 0.01). Absence of a supported difference is not proof of equality (323 test queries).
"""
    tldr = (f"* **Stemmed Stage 1 (section 10):** Recall@100 (micro, test) {u_te['recall@100_micro']:.4f} -> {s_te['recall@100_micro']:.4f}, queries without a relevant candidate "
            f"{u_te['frac_queries_no_relevant_candidate']:.3f} -> {s_te['frac_queries_no_relevant_candidate']:.3f}; stemmed BM25 alone vs unstemmed BM25: NDCG@10 {st_v['ndcg10']['verdict']}, AP {st_v['ap']['verdict']}. "
            f"Learned models on the stemmed candidates beat unstemmed BM25 for {n_a_nd} of 3 (NDCG@10), but differ from stemmed BM25 alone in a supported way for {3 - n_b_nd} of 3 (NDCG@10) and {3 - n_b_ap} of 3 (AP).")
    return text, tldr
